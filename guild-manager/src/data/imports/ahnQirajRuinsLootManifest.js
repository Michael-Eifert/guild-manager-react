export const unsupportedAhnQirajRuinsDrops = Object.freeze(
  AHN_QIRAJ_RUINS_ACTIVE_LOOT_MANIFEST.filter((entry) => entry.unsupportedSlot).map(
    (entry) => ({
      internalId: entry.internalId,
      name: entry.name,
      unsupportedSlot: entry.unsupportedSlot,
      sourceBosses: [...entry.sourceBosses],
    }),
  ),
);

export const convertAhnQirajRuinsManifestEntry = (entry) => ({
  id: entry.internalId ?? entry.wowheadId,
  name: entry.name,
  slot: entry.slot,
  quality: entry.quality,
  type: entry.type,
  minLevel: entry.minLevel,
  dungeonSetId: AHN_QIRAJ_RUINS_SET_ID,
  dungeonSetName: AHN_QIRAJ_RUINS_SET_NAME,
  sourceBosses: [...entry.sourceBosses],
  allowedClasses: Array.isArray(entry.allowedClasses)
    ? [...entry.allowedClasses]
    : undefined,
  internalId: entry.internalId,
  icon: wowItemIcon(entry.iconCode),
  stats: entry.stats ? { ...entry.stats } : undefined,
});

export const AHN_QIRAJ_RUINS_ITEMS = Object.freeze(
  AHN_QIRAJ_RUINS_ACTIVE_LOOT_MANIFEST
    .filter((entry) => ACTIVE_EQUIPMENT_SLOTS.includes(entry.slot))
    .map(convertAhnQirajRuinsManifestEntry),
);
