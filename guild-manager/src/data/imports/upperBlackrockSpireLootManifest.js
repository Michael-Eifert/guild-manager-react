export const convertUpperBlackrockSpireManifestEntry = (entry) => ({
  id: entry.wowheadId,
  name: entry.name,
  slot: entry.slot,
  quality: entry.quality,
  type: entry.type,
  minLevel: entry.minLevel,
  dungeonSetId: BLACKROCK_SPIRE_SET_ID,
  dungeonSetName: BLACKROCK_SPIRE_SET_NAME,
  dungeonWing: UPPER_BLACKROCK_SPIRE_WING_NAME,
  sourceBosses: [...entry.sourceBosses],
  allowedClasses: Array.isArray(entry.allowedClasses)
    ? [...entry.allowedClasses]
    : undefined,
  wowheadId: entry.wowheadId,
  icon: wowItemIcon(entry.iconCode),
  setId: entry.setId,
  setName: entry.setName,
  stats: entry.stats ? { ...entry.stats } : undefined,
});

